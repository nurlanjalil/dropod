import AppKit

/// Notices text you copy anywhere, so it can be kept in the Clipboard tab.
/// Needs no permissions: it checks the clipboard's change count twice a second.
final class ClipboardWatcher {
    static let shared = ClipboardWatcher()

    /// The most a clip keeps; longer copies are cut (and marked as cut).
    static let maxLength = 100_000

    /// New text, the app it was copied from, and whether it was cut to `maxLength`.
    var onText: ((String, NSRunningApplication?, Bool) -> Void)?

    /// The clipboard being watched (a private one in tests).
    var pasteboard = NSPasteboard.general
    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    /// Markers apps put on copies that should never be kept: passwords and other secrets
    /// (see nspasteboard.org), and copies that are only temporary.
    private static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
    ]

    var isRunning: Bool { timer != nil }

    func start() {
        guard timer == nil else { return }
        lastChange = pasteboard.changeCount
        let check = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
        RunLoop.main.add(check, forMode: .common)
        timer = check
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Dropod just wrote to the clipboard itself (copying a clip back): don't record it again.
    func skipCurrent() { lastChange = pasteboard.changeCount }

    func check() {
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount

        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        // Copied files (⌘C in Finder) are files, not text.
        guard !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }
        guard let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let cut = text.count > Self.maxLength
        onText?(cut ? String(text.prefix(Self.maxLength)) : text, NSWorkspace.shared.frontmostApplication, cut)
    }
}
